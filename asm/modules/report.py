import json
from pathlib import Path
from datetime import datetime, timezone

from asm import db

REPORTS_DIR = Path("reports")

SEVERITY_ORDER = ["critical", "high", "medium", "low", "info"]
SEVERITY_EMOJI = {
    "critical": "🔴", "high": "🟠", "medium": "🟡", "low": "🔵", "info": "⚪",
}


def write_json_report(summary: dict, path: Path) -> None:
    with open(path, "w") as f:
        json.dump(summary, f, indent=2, default=str)


def _severity_counts(findings: list[dict]) -> dict:
    counts = {}
    for f in findings:
        counts[f["severity"]] = counts.get(f["severity"], 0) + 1
    return counts


def write_markdown_report(summary: dict, path: Path) -> None:
    scan = summary["scan"]
    findings = summary["findings"]
    lines = []

    # --- Header ---
    lines.append(f"# Attack Surface Report — {scan.get('target', 'unknown')}")
    lines.append("")
    lines.append(f"- **Scan ID:** {scan.get('id')}")
    lines.append(f"- **Started:** {scan.get('started_at')}")
    lines.append(f"- **Finished:** {scan.get('finished_at')}")
    lines.append(f"- **Generated:** {datetime.now(timezone.utc).isoformat()}")
    lines.append("")

    # --- Executive summary (counts) ---
    lines.append("## Summary")
    lines.append("")
    lines.append(f"| Asset type | Count |")
    lines.append(f"|---|---|")
    lines.append(f"| Subdomains discovered | {len(summary['subdomains'])} |")
    lines.append(f"| Live web hosts | {len(summary['hosts'])} |")
    lines.append(f"| Open services | {len(summary['services'])} |")
    lines.append(f"| Cloud assets | {len(summary['cloud_assets'])} |")
    lines.append(f"| Endpoints | {len(summary['endpoints'])} |")
    lines.append(f"| Secrets flagged | {len(summary['secrets'])} |")
    lines.append(f"| **Total findings** | **{len(findings)}** |")
    lines.append("")

    # --- Findings by severity ---
    sev_counts = _severity_counts(findings)
    if sev_counts:
        badge = " · ".join(
            f"{SEVERITY_EMOJI.get(s,'')} {s.capitalize()}: {sev_counts[s]}"
            for s in SEVERITY_ORDER if s in sev_counts
        )
        lines.append(f"**Findings by severity:** {badge}")
        lines.append("")

    # --- Findings detail (the important part, severity-ordered) ---
    lines.append("## Findings")
    lines.append("")
    if not findings:
        lines.append("_No findings generated by correlation rules._")
        lines.append("")
    else:
        for f in findings:
            emoji = SEVERITY_EMOJI.get(f["severity"], "")
            lines.append(f"### {emoji} [{f['severity'].upper()}] {f['title']}")
            lines.append("")
            lines.append(f"- **Category:** {f['category']}")
            lines.append(f"- **Correlation:** `{f['correlation_type']}`")
            lines.append(f"- **Evidence:** {f['evidence']}")
            lines.append("")

    # --- Appendix: recon data (collapsed-friendly) ---
    lines.append("## Appendix — Recon Data")
    lines.append("")

    # Cloud assets
    if summary["cloud_assets"]:
        lines.append("### Cloud Assets")
        lines.append("")
        lines.append("| Identifier | Provider | Type | Public | Takeover? |")
        lines.append("|---|---|---|---|---|")
        for a in summary["cloud_assets"]:
            lines.append(f"| {a['identifier']} | {a['provider']} | {a['type']} | "
                         f"{'yes' if a['public'] else 'no'} | "
                         f"{'⚠ yes' if a['takeover_candidate'] else 'no'} |")
        lines.append("")

    # Live hosts (cap to keep report readable)
    if summary["hosts"]:
        lines.append(f"### Live Hosts ({len(summary['hosts'])} total, showing up to 50)")
        lines.append("")
        lines.append("| URL | Status | Server | Tech |")
        lines.append("|---|---|---|---|")
        for h in summary["hosts"][:50]:
            lines.append(f"| {h['url']} | {h['status_code'] or ''} | "
                         f"{h['server'] or ''} | {h['tech'] or ''} |")
        lines.append("")

    # Services
    if summary["services"]:
        lines.append("### Open Services")
        lines.append("")
        lines.append("| IP | Port | Service | Version |")
        lines.append("|---|---|---|---|")
        for s in summary["services"]:
            lines.append(f"| {s['ip']} | {s['port']} | {s['service'] or ''} | {s['version'] or ''} |")
        lines.append("")

    # Secrets (always show if any — redacted)
    if summary["secrets"]:
        lines.append("### Flagged Secrets (redacted)")
        lines.append("")
        lines.append("| Type | Redacted | Location | Severity |")
        lines.append("|---|---|---|---|")
        for s in summary["secrets"]:
            lines.append(f"| {s['type']} | `{s['value_redacted']}` | {s['location']} | {s['severity']} |")
        lines.append("")

    with open(path, "w") as f:
        f.write("\n".join(lines))


def generate_reports(scan_id: int) -> None:
    summary = db.get_scan_summary(scan_id)
    scan = summary["scan"]
    if not scan:
        print(f"[report] No scan with id {scan_id}")
        return

    REPORTS_DIR.mkdir(exist_ok=True)
    target = (scan.get("target") or "unknown").replace(".", "_")
    base = f"report_{target}_{scan_id}"

    json_path = REPORTS_DIR / f"{base}.json"
    md_path = REPORTS_DIR / f"{base}.md"

    write_json_report(summary, json_path)
    write_markdown_report(summary, md_path)

    print(f"[report] JSON  → {json_path}")
    print(f"[report] Markdown → {md_path}")
    print(f"[report] {len(summary['findings'])} findings across "
          f"{len(summary['subdomains'])} subdomains, {len(summary['hosts'])} live hosts")


if __name__ == "__main__":
    import sys
    if len(sys.argv) < 2:
        print("Usage: python -m asm.modules.report <scan_id>")
        sys.exit(1)
    generate_reports(int(sys.argv[1]))
